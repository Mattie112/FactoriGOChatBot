// This is more of an integration test, it actually creates (and tails) a file
func Test_processLogLines(t *testing.T) {
	config = botConfig{}
	// Prepare channel (processLogLines will publish to this one)
	messagesToDiscord = make(chan string, 100)

	// First write a file with some lines so that we have a baseline, these must not be reported
	filename := filepath.Join(t.TempDir(), "console.log")
	if err := os.WriteFile(filename, []byte("2022-02-01 15:31:30 [CHAT] Mattie: Old message\n"), 0644); err != nil {
		t.Fatal(err)
	}

	tailFile, err := tailLogFile(filename)
	if err != nil {
		t.Fatal(err)
	}
	done := make(chan struct{})
	go func() {
		processLogLines(tailFile)
		close(done)
	}()

	f, err := os.OpenFile(filename, os.O_APPEND|os.O_WRONLY, 0600)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = f.Close() }()
	appendToLog := func(text string) {
		if _, err := f.WriteString(text); err != nil {
			t.Fatal(err)
		}
	}
	want := ":speech_left: | `Mattie`: Some chat message"

	// The file is opened in the background, so keep writing lines (like Factorio would) until one is picked up
	timeout := time.After(10 * time.Second)
	received := false
	for !received {
		appendToLog("2022-02-01 15:31:30 [CHAT] Mattie: Some chat message\n")
		select {
		case got := <-messagesToDiscord:
			if got != want {
				t.Fatalf("processLogLines() = '%v', want '%v'", got, want)
			}
			received = true
		case <-timeout:
			t.Fatal("Timeout while waiting for a line from the log file")
		case <-time.After(50 * time.Millisecond):
		}
	}

	// A line that is still being written must only be reported when it is complete
	appendToLog("2022-02-01 15:31:31 [CHAT] Mattie: Partial")
	appendToLog(" line\n")
	wantPartial := ":speech_left: | `Mattie`: Partial line"
	for received = false; !received; {
		select {
		case got := <-messagesToDiscord:
			if got == want {
				continue // One of the other lines
			}
			if got != wantPartial {
				t.Fatalf("processLogLines() = '%v', want '%v'", got, wantPartial)
			}
			received = true
		case <-timeout:
			t.Fatal("Timeout while waiting for the partial line from the log file")
		case <-time.After(100 * time.Millisecond):
			// Right after startup the tail library can miss a write (it happened just before it started
			// watching the file), it catches up on the next write
			appendToLog("2022-02-01 15:31:30 [CHAT] Mattie: Some chat message\n")
		}
	}

	// Stopping the tail must end the processing
	_ = tailFile.Stop()
	select {
	case <-done:
	case <-timeout:
		t.Fatal("Timeout while waiting for processLogLines() to stop")
	}
}

